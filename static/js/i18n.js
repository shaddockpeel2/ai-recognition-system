// ===== i18n 核心引擎 =====
const i18n = (function() {
    // 读取语言：优先localStorage，其次server config，默认中文
    function detectLanguage() {
        return localStorage.getItem('safehat_language') || 'zh-CN';
    }

    let currentLang = detectLanguage();

    function t(key, vars) {
        const dict = I18N_TRANSLATIONS[currentLang] || I18N_TRANSLATIONS['zh-CN'];
        // 用 hasOwnProperty 避免空字符串被 || 误判为 falsy
        let text = (dict && Object.prototype.hasOwnProperty.call(dict, key))
            ? dict[key]
            : (Object.prototype.hasOwnProperty.call(I18N_TRANSLATIONS['zh-CN'], key)
                ? I18N_TRANSLATIONS['zh-CN'][key]
                : key);
        if (vars) {
            Object.keys(vars).forEach(k => {
                text = text.replace('{' + k + '}', vars[k]);
            });
        }
        return text;
    }

    function lang() {
        return currentLang;
    }

    function setLang(newLang) {
        if (newLang === currentLang) return;
        currentLang = newLang;
        localStorage.setItem('safehat_language', newLang);
    }

    // 应用翻译到DOM中带有 data-i18n 属性的元素
    function apply(container) {
        // 同步 HTML lang 属性，让浏览器正确渲染 datetime-local 等表单的语言格式
        if (!container) {
            document.documentElement.lang = currentLang === 'en-US' ? 'en' : 'zh-CN';
        }
        const root = container || document;
        root.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translated = t(key);
            // 如果元素只含文本节点，替换textContent；否则替换innerHTML
            if (el.children.length === 0) {
                el.textContent = translated;
            } else {
                // 只替换直接文本节点，不影响子元素
                el.childNodes.forEach(node => {
                    if (node.nodeType === Node.TEXT_NODE && node.textContent.trim()) {
                        node.textContent = translated;
                    }
                });
            }
        });

        // 处理 data-i18n-placeholder（输入框占位符）
        root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
        });

        // 处理 data-i18n-title（tooltip）
        root.querySelectorAll('[data-i18n-title]').forEach(el => {
            el.title = t(el.getAttribute('data-i18n-title'));
        });
    }

    return { t, lang, setLang, apply, detectLanguage };
})();

// 全局快捷函数
window.i18n = i18n;
window.t = function(key, vars) { return i18n.t(key, vars); };

// DOM 加载后自动应用翻译
document.addEventListener('DOMContentLoaded', function() {
    i18n.apply();
});
